//
// 判定は **err.status（数値）** で行う。文言でのマッチをしない
// （detail の文言はサーバー側の都合で変わりうる）。
//
// - 401（セッション失効・未ログイン）: 全画面をログイン導線に置き換える。
//   全画面置換を許すのは 401 のときだけ
// - それ以外（403 / 404 / 500 / ネットワーク断）: その場（グリッド内）に
//   留めて再試行を出す。画面全体を消さない（P1-12）

export function errorDisposition(status) {
  return status === 401 ? "login" : "stay";
}

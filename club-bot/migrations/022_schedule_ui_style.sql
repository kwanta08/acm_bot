-- =====================================================================
-- 022_schedule_ui_style.sql
--
-- 日程調整の投票 UI 方式（スキーマバージョン 23）。
--
-- 背景:
--   従来は候補日ごとに1メッセージを投稿しリアクションで投票していたが、
--   候補が縦に並んで見比べられないため、全候補を1メッセージに集約し
--   ボタンで投票する方式を追加した。既存の投稿済みメッセージは
--   リアクションのまま動き続ける必要があるので、どちらの方式で
--   投稿されたかを予定ごとに記録する。
--
-- schedules.ui_style:
--   'reaction' … 候補ごとに1メッセージ＋リアクション投票（従来）
--   'buttons'  … 全候補を1メッセージに集約＋ボタン投票
--
-- 既存行はすべて 'reaction'（投稿済みメッセージの挙動を変えない）。
-- 新規作成時の方式はギルド別設定 SCHEDULE_UI_STYLE で決まる（既定 buttons）。
--
-- 実際の適用は utils/db.py の _migrate_v23_schedule_ui_style() が行う
-- （列の有無を確認してから ALTER する冪等な実装）。このファイルは
-- 変更内容の記録用。
-- =====================================================================

ALTER TABLE schedules ADD COLUMN ui_style TEXT NOT NULL DEFAULT 'reaction';
